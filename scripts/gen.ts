// Embeds templates/*.toml and presets/presets.json into src/assets.gen.ts, so the
// compiled binary needs no files beside it. Run with `deno task gen`.
const root = new URL("..", import.meta.url);
const read = (path: string) => Deno.readTextFileSync(new URL(path, root));

const source = `// Generated by scripts/gen.ts from templates/ and presets/. Do not edit.
import type { Preset } from "./presets.ts";

export const SHELL_TEMPLATE: string = ${JSON.stringify(read("templates/shell.toml"))};

export const BAR_TEMPLATE: string = ${JSON.stringify(read("templates/statusline.toml"))};

export const PRESETS: Preset[] = ${read("presets/presets.json").trim()};
`;

const out = new URL("src/assets.gen.ts", root);
const current = (() => {
  try {
    return Deno.readTextFileSync(out);
  } catch {
    return "";
  }
})();

if (Deno.args.includes("--check")) {
  if (current !== source) {
    console.error("src/assets.gen.ts is out of date: run `deno task gen`");
    Deno.exit(1);
  }
} else {
  Deno.writeTextFileSync(out, source);
  console.log("wrote src/assets.gen.ts");
}
